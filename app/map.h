//##############################################################################
//####
//####    >>>坐标轴约定<<<
//####
//  采用右手坐标系（场地俯视）：
//    X轴 → 左右方向（向右为正）
//    Y轴 → 前进方向（从启动区指向归位区，向前为正）
//    W轴 → 偏航角（°），向左转为正
//
//  若实测发现轴向相反，只需将对应 ORIGIN/SPACING 取反即可。
//
//  场地示意（俯视）：
//
//    归位区:  [21][22][23][24]         Y
//             ──── 减速带 ────          ↑
//    存放区:  [5] [6] [7] [8]  row=1  │
//             [1] [2] [3] [4]  row=0  └──→ X
//              col: 0   1   2   3
//    启动区（机器人从此出发，Y最小）
//
//  ID编码：
//    存放区 ID 1~8  : ID = row*STORAGE_COLS + col + 1
//    归位区 ID 21~24: ID = idx + 21  (idx=0最左)
//##############################################################################

//##############################################################################
//####  >>>存放区物理参数<<<  （现场标定后填入，单位 mm）
//##############################################################################
#define STORAGE_ROWS        2           // 行数（沿Y轴）
#define STORAGE_COLS        4           // 列数（沿X轴）
#define STORAGE_SPACING_X   600.0f      // 列间距(mm)  已确认
#define STORAGE_SPACING_Y   600.0f      // 行间距(mm)  已确认
#define STORAGE_ORIGIN_X    0.0f        // ID=1 中心X ← 雷达装好后标定
#define STORAGE_ORIGIN_Y    0.0f        // ID=1 中心Y ← 雷达装好后标定

//##############################################################################
//####  >>>归位区物理参数<<<  （现场标定后填入，单位 mm）
//##############################################################################
#define RETURN_COLS         4           // 归位格数量
#define RETURN_SPACING_X    400.0f      // 归位格间距(mm)  已确认
#define RETURN_ORIGIN_X     0.0f        // idx=0(ID=21)中心X ← 雷达装好后标定
#define RETURN_Y            0.0f        // 归位区Y坐标 ← 雷达装好后标定

//##############################################################################
//####  >>>取货朝向<<<  （现场调试后填入）
//##############################################################################
#define YAW_FACE_BOXES      0.0f        // 取货时机器人朝向（°）← 现场标定

//##############################################################################
//####  >>>摄像头精对准目标值<<<  （调试后填入）
//##############################################################################
#define CAMERA_PICK_X       1.0f        // weapon_x 目标值 ← 调试
#define CAMERA_PICK_Y       20.0f       // weapon_y 目标值 ← 调试

//##############################################################################
//####  >>>数据结构<<<
//##############################################################################
typedef struct {
    float center_x;     // 格子中心X（mm）
    float center_y;     // 格子中心Y（mm）
} BoxSlot_t;

//##############################################################################
//####  >>>外部变量<<<
//##############################################################################
extern BoxSlot_t  Storage_Map[STORAGE_ROWS][STORAGE_COLS];
extern BoxSlot_t  Return_Map[RETURN_COLS];
extern Waypoint_t Dynamic_WP;
extern uint8_t    task_step;            // 0=空闲，>0=任务进行中
extern float      target_yaw;
extern Robot_Upper_State cmd_action;    // 当前任务的动作类型
extern uint8_t           cmd_map_id;    // 当前任务的目标ID

//##############################################################################
//####  >>>函数声明<<<
//##############################################################################
// 上电时调用一次
void    Field_Map_Init(void);

// 坐标查询（纯数学，无越界风险）
float   Get_Storage_X(int8_t r, int8_t c);
float   Get_Storage_Y(int8_t r, int8_t c);
float   Get_Return_X(uint8_t idx);

// 外部接口：通信层收到新指令时调用此函数
// id: 目标格子ID（1~8取货，21~24放货）
// act: 到达后执行的动作（来自 Robot_Upper_State 枚举）
void    Map_Set_Command(uint8_t id, Robot_Upper_State act);

// 内部驱动：每控制周期调用
uint8_t Nav_Task_Loop(void);

#endif

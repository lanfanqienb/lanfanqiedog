#ifndef __RUN_H
#define __RUN_H

#include "main.h"

//##############################################################################
//####
//####    >>>跑点状态机<<<
//####
//##############################################################################
typedef enum {
    DOT_IDLE  = 0,   // 空闲，等待新任务
    DOT_INIT  = 1,   // 初始化：锁定传感器起始值
    DOT_MOVE  = 2,   // 运动中：持续调用 Chassis_move()
    DOT_DELAY = 3,   // 到位缓冲：短暂延时后通知上位机
    DOT_UPPER = 4,   // 执行上部动作：等待动作完成
    DOT_DONE  = 5,   // 完成：复位状态，返回 1
} Dot_State_e;

//##############################################################################
//####
//####    >>>机器人整体状态<<<
//####
//##############################################################################
typedef enum {
    FREE = 0,   // 空闲
    MOVE = 1,   // 运动中
    SUCC = 2,   // 成功
    FAIL = 3,   // 失败
} Robot_State;

//##############################################################################
//####
//####    >>>路径点传感器模式<<<
//####
//  决定这个路径点用哪个传感器做闭环
//##############################################################################
typedef enum {
    EMPTY   = 0,   // 空点，直接跳过（task_step 占位用）
    RADAR   = 1,   // 雷达全局坐标闭环（Global_x/y）
    CAMERA  = 2,   // 摄像头视觉闭环（weapon_x/y）
    NO_MOVE = 3,   // 不移动，直接执行动作
} Robot_Dot_mode;

//##############################################################################
//####
//####    >>>上部机构动作<<<
//####
//  到达路径点后需要执行的动作
//  根据比赛需求扩充，与上位机协议保持一致
//##############################################################################
typedef enum {
    UPPER_FREE  = 0,   // 无动作
    PICK_BOX    = 1,   // 抓取箱子
    PLACE_BOX   = 2,   // 放置箱子
} Robot_Upper_State;

//##############################################################################
//####
//####    >>>路径点结构体<<<
//####
//  map.c 每步填充一个，传给 Dot_Run() 执行
//##############################################################################
#pragma pack(1)
typedef struct {
    float             x;            // 目标X坐标（mm，雷达模式）或视觉偏差（摄像头模式）
    float             y;            // 目标Y坐标
    float             w;            // 目标朝向角（°）
    Robot_Dot_mode    mode;         // 用哪个传感器
    Robot_Upper_State action_type;  // 到位后执行什么动作
} Waypoint_t;
#pragma pack()

//##############################################################################
//####
//####    >>>软件定时器（非阻塞延时）<<<
//####
//##############################################################################
typedef struct {
    uint32_t start_tick;
    uint8_t  is_running;
} SoftTimer_t;

//##############################################################################
//####
//####    >>>外部变量声明<<<
//####
//  Global_x/y/w  由雷达解析模块定义（usart_app.c 或 radar.c）
//  weapon_x/y    由摄像头模块定义
//##############################################################################
extern float       Global_x;             // 雷达：当前X坐标（mm）
extern float       Global_y;             // 雷达：当前Y坐标（mm）
extern float       Global_w;             // 雷达/陀螺仪：当前朝向角（°）
extern float       weapon_x;             // 摄像头：目标X偏差
extern float       weapon_y;             // 摄像头：目标Y偏差

extern uint8_t          mode;                  // 主控制模式（3=导航行走，1=IK站立）
extern Robot_State      Robot_chassis_state;   // 底盘状态（外部置 MOVE 触发导航）
extern Robot_State      Robot_system_state;    // 整车全局状态（map.c 读取）
extern Robot_Upper_State Robot_upper_state;    // 当前上部动作状态
extern Dot_State_e      dot_state;             // 跑点状态机当前状态

//##############################################################################
//####
//####    >>>函数声明<<<
//####
//##############################################################################
uint8_t Dot_Run(Waypoint_t* path);              // 跑点主函数，每周期调用
uint8_t Upper_Execute(Robot_Upper_State act);   // 分发上部动作
void    Robot_System_State_Monitor(void);       // 更新 Robot_system_state

#endif
